async function resolveStatic(out, pathname) {
  let decoded;
  try {
    decoded = decodeURIComponent(pathname);
  } catch {
    return void 0;
  }
  const segments = decoded.split("/").filter(Boolean);
  if (!segments.length || segments.some((part) => part === ".." || part.startsWith(".")))
    return void 0;
  if (segments.some((part) => part.includes("\\") || part.includes("\0"))) return void 0;
  const file = path6.join(out, ...segments);
  if (!isWithin(out, file)) return void 0;
  const found = await stat2(file).catch(() => void 0);
  return found?.isFile() ? file : void 0;
}
