async function runRepositoryServer(args, root = process.cwd()) {
  const { values } = parseArgs({
    args,
    options: {
      port: { type: "string", default: "7420" },
      cert: { type: "string" },
      key: { type: "string" },
      host: { type: "string" },
      "public-url": { type: "string" },
      history: { type: "string", default: HISTORY },
      fresh: { type: "boolean", default: false },
      "index-status": { type: "string" },
      delay: { type: "string", default: "0" },
      "no-etag": { type: "boolean", default: false }
    }
  });
  if (values.cert === void 0 !== (values.key === void 0))
    throw new Error("--cert and --key must be passed together");
  const publicUrl = values["public-url"];
  if (publicUrl !== void 0 && new URL(publicUrl).protocol !== "https:")
    throw new Error("--public-url must be an HTTPS URL; Snow refuses plain HTTP");
  const indexStatus = values["index-status"] === void 0 ? void 0 : Number(values["index-status"]);
  if (indexStatus !== void 0 && !(Number.isInteger(indexStatus) && indexStatus >= 200 && indexStatus <= 599))
    throw new Error("--index-status must be an HTTP status code");
  const tls = values.cert && values.key ? { cert: await readFile4(values.cert, "utf8"), key: await readFile4(values.key, "utf8") } : void 0;
  return startRepositoryServer({
    root,
    port: Number(values.port),
    // Plain HTTP stays on loopback, where only a tunnel can reach it.
    host: tls ? values.host ?? "0.0.0.0" : "127.0.0.1",
    tls,
    publicUrl,
    history: values.history,
    fresh: values.fresh,
    indexStatus,
    delayMs: Number(values.delay),
    etag: !values["no-etag"]
  });
}

