var MAX_VERSION_LENGTH = 64;
var MAX_RANGE_LENGTH = 128;
var MAX_COMPARATORS = 8;
var MAX_SEGMENT = 999999999;
var MANIFEST_VERSION = /^((?:0|[1-9]\d*)(?:\.(?:0|[1-9]\d*)){0,3})(?:-([0-9A-Za-z.]{1,32}))?(?:\+([0-9A-Za-z.-]{1,64}))?$/;
