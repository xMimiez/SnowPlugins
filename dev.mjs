var DEFAULT_MAXIMUM_OUTPUT_BYTES = 64 * 1024 * 1024;
async function readBounded(stream, budget, terminate) {
  const reader = stream.getReader();
  const chunks = [];
  try {
    for (; ; ) {
      const { done, value } = await reader.read();
      if (done) break;
      budget.bytes += value.byteLength;
      if (budget.bytes > budget.maximum) {
        terminate();
        throw new Error(`Process output exceeded ${budget.maximum} bytes`);
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  return Buffer.concat(chunks);
}
async function runProcess(command, options = {}) {
  const maximum = options.maximumOutputBytes ?? DEFAULT_MAXIMUM_OUTPUT_BYTES;
  const child = Bun.spawn([...command], {
    cwd: options.cwd,
    stderr: "pipe",
    stdout: "pipe"
  });
  const budget = { bytes: 0, maximum };
  const terminate = () => child.kill();
  const [exitCode, stderr, stdout] = await Promise.all([
    child.exited,
    readBounded(child.stderr, budget, terminate),
    readBounded(child.stdout, budget, terminate)
  ]);
  if (exitCode !== 0 && !options.allowFailure) {
    const message = new TextDecoder().decode(stderr).trim();
    throw new Error(
      `${command[0]} exited with code ${exitCode}${message ? `: ${message}` : ""}`
    );
  }
  return { exitCode, stderr, stdout };
}
