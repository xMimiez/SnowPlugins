var MAX_VERSION_LENGTH2 = 64;
var MAX_RANGE_LENGTH = 128;
var MAX_COMPARATORS = 8;
var MAX_SEGMENT = 999999999;
var MANIFEST_VERSION = /^((?:0|[1-9]\d*)(?:\.(?:0|[1-9]\d*)){0,3})(?:-([0-9A-Za-z.]{1,32}))?(?:\+([0-9A-Za-z.-]{1,64}))?$/;
var COMPARATOR = /^(>=|<=|>|<|=)?(.+)$/;
function versionFrom(text, numbers, prerelease) {
  const segments = numbers.split(".").map(Number);
  if (segments.some((segment) => segment > MAX_SEGMENT)) {
    throw new Error(`Version segments must be at most ${MAX_SEGMENT}`);
  }
  const tag = prerelease?.split(".") ?? [];
  if (tag.some((part) => part.length === 0)) {
    throw new Error("Version prerelease tags must not contain empty parts");
  }
  return { segments, prerelease: tag, text };
}
function parseVersion(text) {
  const match = text.length <= MAX_VERSION_LENGTH2 ? MANIFEST_VERSION.exec(text) : null;
  if (!match) throw new Error(`Invalid version ${JSON.stringify(text)}`);
  return versionFrom(text, match[1], match[2]);
}
function parseVersionRange(text, options = {}) {
  if (text.length > MAX_RANGE_LENGTH) {
    throw new Error(`Version ranges must be at most ${MAX_RANGE_LENGTH} characters`);
  }
  if (text === "*") return { comparators: [], text };
  const parts = text.split(/ +/);
  if (parts.length > MAX_COMPARATORS || parts.some((part) => part.length === 0)) {
    throw new Error(
      `Version range ${JSON.stringify(text)} must hold 1 to ${MAX_COMPARATORS} comparators`
    );
  }
  const comparators = parts.map((part) => {
    const [, operator = "=", value] = COMPARATOR.exec(part) ?? [];
    let version;
    try {
      version = parseVersion(value ?? "");
    } catch {
      throw new Error(
        `Version range ${JSON.stringify(text)} is not supported; use comparators such as >=1.2 <2`
      );
    }
    if (version.prerelease.length || version.text.includes("+")) {
      throw new Error("Version range comparators must not carry prerelease or build tags");
    }
    if (options.singleSegment && version.segments.length !== 1) {
      throw new Error("Build range comparators must be a single number");
    }
    return { operator, version };
  });
  return { comparators, text };
}

